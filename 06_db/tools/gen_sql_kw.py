#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
生成 db_sql_kw.h —— 将 SQL 关键字编码为 XOR(0x5A) 密文数组。
用法: python3 gen_sql_kw.py > db_sql_kw.h

约定：
  - len 字段 = 字符串长度（不含终止符）
  - data 数组不含终止符字节（解码器负责追加 \0）
"""
import sys

KEY = 0x5A

# 与 include/db_sql_kw.h 中的宏索引一一对应
KW = [
    "PRAGMA journal_mode=WAL;",
    "PRAGMA synchronous=NORMAL;",
    "PRAGMA temp_store=MEMORY;",
    "PRAGMA cache_size=-64000;",
    "BEGIN IMMEDIATE",
    "COMMIT",
    "ROLLBACK",
    "SAVEPOINT sp_%d",
    "RELEASE SAVEPOINT sp_%d",
    "ROLLBACK TO SAVEPOINT sp_%d",
    "VACUUM",
    "VACUUM INTO '%q'",
    "CREATE TABLE IF NOT EXISTS",
    "INSERT INTO",
    "SELECT COUNT(*) FROM",
    "SELECT id,name,val FROM",
    "DELETE FROM",
    "DROP TABLE IF EXISTS",
    "SELECT name FROM sqlite_master WHERE",
    " AND name GLOB",
    " VALUES(",
    " VALUES('%s','%s')",
    "=?",
    " ON CONFLICT",
    " DO UPDATE SET",
]

assert len(KW) == 25, f"期望 25 个关键字，实际 {len(KW)}"

def encode(s):
    return [ord(ch) ^ KEY for ch in s]

lines = []
lines.append("/* auto-generated by gen_sql_kw.py -- do not edit */")
lines.append("#ifndef DB_SQL_KW_H")
lines.append("#define DB_SQL_KW_H")
lines.append("")
lines.append("#ifdef __cplusplus")
lines.append("extern \"C\" {")
lines.append("#endif")
lines.append("")

# 宏定义（下划线后为两位数字索引）
for i, s in enumerate(KW):
    lines.append(f"#define DB_KW_{i:02d}  {i}")
lines.append(f"#define DB_SQL_KW_COUNT  {len(KW)}")
lines.append("")

# 结构体
lines.append("struct db_kw {")
lines.append("    int len;")
lines.append("    const unsigned char *data;")
lines.append("};")
lines.append("")

# 表：{ len, (const unsigned char[]){...密文...} }
lines.append("static const struct db_kw db_sql_kw_table[DB_SQL_KW_COUNT] = {")
for i, s in enumerate(KW):
    enc = encode(s)
    enc_str = ",".join(str(b) for b in enc)
    lines.append(f"    {{{len(s)}, (const unsigned char[]){{{enc_str}}}}},   /* {i:2d}: {s} */")
lines.append("};")
lines.append("")

lines.append("#ifdef __cplusplus")
lines.append("}")
lines.append("#endif")
lines.append("")
lines.append("#endif /* DB_SQL_KW_H */")

sys.stdout.write("\n".join(lines) + "\n")
