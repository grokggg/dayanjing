/* hs_msgs_real.h —— 真实 TLS 客户端发出的后续握手记录（抓包固化）
 *
 * 抓取方式：scripts/capture_hs_msgs.py 做 TCP 中转，OpenSSL 3.0.2 的
 * s_client（-tls1_2 -cipher ECDHE-RSA-AES128-GCM-SHA256 -curves X25519）
 * 连进来，双向字节流原样落盘后按记录头切分。
 *
 * 为什么必须抓真报文而不是手写：
 *   手写出来的 ClientHello 只会包含我们想到的字段。而解析器真正会崩在
 *   没想到的字段上 —— 手写的基底天然覆盖不到那些地方。CKE 同理：它的
 *   内部形态（这里是 X25519，1 字节长度 + 32 字节 point）取决于协商结果，
 *   不是拍脑袋定的。
 *
 * 为什么只固化这两条：
 *   CCS 之后就进入加密，后续记录（Finished / 应用数据）在线路上不可解析。
 *   ClientHello 与 ClientKeyExchange 是「明文且由解析器先行处理」的全部
 *   客户端消息 —— 服务端能被打穿的入口就这两个。
 *
 * 注意：这是某一天观察到的 OpenSSL 3.0.2 行为快照。换实现或升级后必须
 * 重抓，本文件不会自动更新。
 */
